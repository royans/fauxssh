    def handle_hostname(self, cmd, context):
        # Use persona hostname if available
        # Structure is persona -> system -> hostname
        sys_conf = config.get("persona", "system") or {}
        h = (
            sys_conf.get("hostname")
            or config.get("server", "hostname")
            or "npc-main-server-01"
        )

        # Parse basic args
        parts = cmd.split()
        if len(parts) > 1:
            if parts[1].startswith("-"):
                # -f, -i, etc. Just ignore or return standard
                if "i" in parts[1]:
                    return (
                        f"{context.get('honeypot_ip', '127.0.0.1')}\n",
                        {},
                        {"source": "handler", "cached": False},
                    )
            else:
                # Attempt to set hostname -> Permission denied (unless root)
                if context.get("user") != "root":
                    if "2>/dev/null" in cmd:
                        return (
                            "",
                            {},
                            {"source": "handler", "cached": False},
                        )
                    return (
                        f"hostname: you must be root to change the host name\n",
                        {},
                        {"source": "handler", "cached": False},
                    )
                else:
                    # Fake set success (no persistence)
                    return "", {}, {"source": "handler", "cached": False}

        return (
            f"{h}\n",
            {},
            {"source": "handler", "cached": False},
        )

    def handle_uname(self, cmd, context):
        # Default: Linux
        kernel_name = "Linux"
        sys_conf = config.get("persona", "system") or {}
        nodename = (
            sys_conf.get("hostname")
            or config.get("server", "hostname")
            or "npc-main-server-01"
        )

        kernel_release = "5.10.0-21-cloud-amd64"
        kernel_version = "#1 SMP Debian 5.10.162-1 (2023-01-21)"
        machine = "x86_64"
        processor = "x86_64"
        hardware_platform = "x86_64"
        os_name = "GNU/Linux"

        parts = cmd.split()
        flags = set()
        for p in parts[1:]:
            if p.startswith("-"):
                for char in p[1:]:
                    flags.add(char)

        # If no flags, default is -s (Kernel name)
        if not flags:
            return f"{kernel_name}\n", {}, {"source": "handler", "cached": False}

        if "a" in flags or "all" in flags:  # -a is --all
            return (
                f"{kernel_name} {nodename} {kernel_release} {kernel_version} {machine} {os_name}\n",
                {},
                {"source": "handler", "cached": False},
            )

        out = []
        if "s" in flags:
            out.append(kernel_name)
        if "n" in flags:
            out.append(nodename)
        if "r" in flags:
            out.append(kernel_release)
        if "v" in flags:
            out.append(kernel_version)
        if "m" in flags:
            out.append(machine)
        if "p" in flags:
            out.append(processor)
        if "i" in flags:
            out.append(hardware_platform)
        if "o" in flags:
            out.append(os_name)

        if not out:  # Default is -s
            return f"{kernel_name}\n", {}, {"source": "handler", "cached": False}

        return (
            " ".join(out) + "\n",
            {},
            {"source": "handler", "cached": False},
        )

    def handle_uptime(self, cmd, context):
        now_dt = datetime.datetime.now()
        now_str = now_dt.strftime("%H:%M:%S")

        # Calculate human friendly uptime from our consistent source
        total_seconds, _ = self._get_uptime_seconds()

        days = int(total_seconds // 86400)
        rem = total_seconds % 86400
        hours = int(rem // 3600)
        minutes = int((rem % 3600) // 60)

        # Randomize load slightly to look alive
        l1 = round(random.uniform(0.01, 0.20), 2)
        l5 = round(random.uniform(0.01, 0.15), 2)
        l15 = round(random.uniform(0.00, 0.10), 2)

        # Format: 17:05:01 up 14 days,  7:22,  2 users,  load average: 0.12, 0.08, 0.02
        return (
            f" {now_str} up {days} days, {hours}:{minutes:02d},  1 user,  load average: {l1:.2f}, {l5:.2f}, {l15:.2f}\n",
            {},
            {"source": "handler", "cached": False},
        )

