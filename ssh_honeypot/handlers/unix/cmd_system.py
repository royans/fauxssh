    def generate_proc_cpuinfo(self):
        # Hardware context from persona
        hw = config.get("persona", "hardware") or {}
        cpu_model = hw.get("cpu_info") or "AMD EPYC 9654 96-Core Processor"

        # Determine core count (naive parse or default 192)
        import re

        cpus = 192
        if "vCPU" in cpu_model:
            try:
                cpus = int(re.search(r"(\d+)", cpu_model).group(1))
            except:
                pass

        out = []
        for i in range(cpus):
            out.append(f"processor\t: {i}")
            out.append(
                "vendor_id\t: AuthenticAMD"
                if "AMD" in cpu_model
                else "vendor_id\t: GenuineIntel"
            )
            out.append("model name\t: " + cpu_model)
            out.append("cpu MHz\t\t: 2400.000")
            out.append("cache size\t: 1024 KB")
            out.append(f"physical id\t: 0")
            out.append(f"siblings\t: {cpus}")
            out.append(f"core id\t\t: {i}")
            out.append(f"cpu cores\t: {cpus}")
            out.append("")
        return "\n".join(out)

