    def _get_ram_info(self):
        hw = config.get("persona", "hardware") or {}
        mem_str = hw.get("memory") or "8GB"

        # Simple parser for "8GB", "256GB" -> KB
        total = 8124220
        import re

        match = re.search(r"(\d+)\s*(GB|MB)", mem_str, re.I)
        if match:
            val = int(match.group(1))
            unit = match.group(2).upper()
            if unit == "GB":
                total = val * 1024 * 1024
            else:
                total = val * 1024

        used = int(total * random.uniform(0.15, 0.40))
        free = int(total * random.uniform(0.10, 0.30))
        buff = total - used - free
        return total, used, free, buff

